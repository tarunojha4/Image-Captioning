"""Evaluation Metrics for Image Captioning.

Implements BLEU-1, BLEU-2, BLEU-3, BLEU-4 scores using NLTK
with fallback smoothing, as well as corpus-level evaluation routines.
"""

from typing import Dict, List, Union
import nltk
from nltk.translate.bleu_score import SmoothingFunction, sentence_bleu

from src.vocab import clean_tokenize


def compute_bleu_scores(
    references: List[Union[str, List[str]]],
    candidate: Union[str, List[str]],
) -> Dict[str, float]:
    """Calculate BLEU-1, BLEU-2, BLEU-3, and BLEU-4 scores for a candidate caption.

    Args:
        references: List of reference captions (either raw strings or tokenized lists).
        candidate: Candidate caption generated by the model.

    Returns:
        Dict containing bleu_1, bleu_2, bleu_3, bleu_4 floats in [0, 1].
    """
    # Standardize references to tokenized lists
    tok_refs: List[List[str]] = []
    for ref in references:
        if isinstance(ref, str):
            tok_refs.append(clean_tokenize(ref))
        else:
            tok_refs.append([w.lower() for w in ref])

    # Standardize candidate
    if isinstance(candidate, str):
        tok_cand = clean_tokenize(candidate)
    else:
        tok_cand = [w.lower() for w in candidate]

    smoothie = SmoothingFunction().method1

    weights = {
        "bleu_1": (1.0, 0.0, 0.0, 0.0),
        "bleu_2": (0.5, 0.5, 0.0, 0.0),
        "bleu_3": (0.333, 0.333, 0.333, 0.0),
        "bleu_4": (0.25, 0.25, 0.25, 0.25),
    }

    scores = {}
    for metric_name, weight_tuple in weights.items():
        try:
            score = sentence_bleu(
                tok_refs,
                tok_cand,
                weights=weight_tuple,
                smoothing_function=smoothie,
            )
        except ZeroDivisionError:
            score = 0.0
        scores[metric_name] = round(score, 4)

    return scores
